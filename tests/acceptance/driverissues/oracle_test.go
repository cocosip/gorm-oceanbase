func oracleTable(t *testing.T, columns string) (*sql.DB, context.Context, string) {
	t.Helper()
	dsn := os.Getenv("OB_ORACLE_DSN")
	if dsn == "" {
		t.Skip("OB_ORACLE_DSN is not configured; live reproduction not run")
	}
	cfg, err := ob.ParseDSN(dsn)
	if err != nil || cfg.Mode != ob.ModeOracle || cfg.CreateDatabaseIfMissing {
		t.Fatal("require an Oracle DSN without createDatabaseIfMissing")
	}
	cfg.ConnectTimeout, cfg.ReadTimeout = 30*time.Second, 30*time.Second
	connector, err := ob.NewConnector(cfg)
	if err != nil {
		t.Fatal("cannot create Oracle connector")
	}
	db := sql.OpenDB(connector)
	t.Cleanup(func() { _ = db.Close() })
	ctx, cancel := context.WithTimeout(context.Background(), time.Minute)
	t.Cleanup(cancel)
	var nonce [6]byte
	if _, err := rand.Read(nonce[:]); err != nil {
		t.Fatal("cannot generate object identity")
	}
	name := "GD" + hex.EncodeToString(nonce[:])
	if _, err := db.ExecContext(ctx, "CREATE TABLE "+name+" ("+columns+")"); err != nil {
		t.Fatalf("create owned table: %s", errorCode(err))
	}
	t.Cleanup(func() {
		cleanupCtx, cleanupCancel := context.WithTimeout(context.Background(), 30*time.Second)
		defer cleanupCancel()
		if _, err := db.ExecContext(cleanupCtx, "DROP TABLE "+name); err != nil {
			t.Errorf("cleanup %s: %s", name, errorCode(err))
		}
	})
	return db, ctx, name
}

func errorCode(err error) string {
	var server *dberrors.Error
	if errors.As(err, &server) {
		return fmt.Sprintf("server code=%d", server.Code)
	}
	if errors.Is(err, dberrors.ErrBind) {
		return "driver ErrBind"
	}
	return fmt.Sprintf("%T (raw message omitted)", err)
}

func TestOracleBinaryDoubleRange(t *testing.T) {
	db, ctx, name := oracleTable(t, "ID NUMBER PRIMARY KEY, V BINARY_DOUBLE")
	values := []float64{1.5, 1.1, 1e200, math.MaxFloat64, -math.MaxFloat64, math.SmallestNonzeroFloat64, -math.SmallestNonzeroFloat64}
	for _, prepared := range []bool{false, true} {
		t.Run(fmt.Sprintf("prepared_%v", prepared), func(t *testing.T) {
			query := "INSERT INTO " + name + " (ID,V) VALUES (?,?)"
			insert := db.ExecContext
			if prepared {
				stmt, err := db.PrepareContext(ctx, query)
				if err != nil {
					t.Fatalf("prepare: %s", errorCode(err))
				}
				defer func() { _ = stmt.Close() }()
				insert = func(ctx context.Context, _ string, args ...any) (sql.Result, error) {
					return stmt.ExecContext(ctx, args...)
				}
			}
			for i, want := range values {
				id := i + 1
				if prepared {
					id += len(values)
				}
				if _, err := insert(ctx, query, id, want); err != nil {
					t.Fatalf("insert %g: %s", want, errorCode(err))
				}
				var got float64
				if err := db.QueryRowContext(ctx, "SELECT V FROM "+name+" WHERE ID=?", id).Scan(&got); err != nil {
					t.Fatalf("read %g: %s", want, errorCode(err))
				}
				if got != want {
					t.Fatalf("roundtrip got=%g want=%g", got, want)
				}
			}
		})
	}
}

func TestOracleBlobBytes(t *testing.T) {
	db, ctx, name := oracleTable(t, "ID NUMBER PRIMARY KEY, V BLOB")
	want := []byte{0, 1, 127, 255}
	for i, tc := range []struct {
		name     string
		value    any
		prepared bool
	}{
		{"bytes_direct", want, false},
		{"bytes_prepared", want, true},
		{"raw_direct_control", types.Raw(want), false},
		{"raw_prepared_control", types.Raw(want), true},
	} {
		t.Run(tc.name, func(t *testing.T) {
			query := "INSERT INTO " + name + " (ID,V) VALUES (?,?)"
			var err error
			if tc.prepared {
				stmt, prepareErr := db.PrepareContext(ctx, query)
				if prepareErr != nil {
					t.Fatalf("prepare: %s", errorCode(prepareErr))
				}
				defer func() { _ = stmt.Close() }()
				_, err = stmt.ExecContext(ctx, i+1, tc.value)
			} else {
				_, err = db.ExecContext(ctx, query, i+1, tc.value)
			}
			if err != nil {
				t.Fatalf("insert: %s", errorCode(err))
			}
			var got []byte
			if err := db.QueryRowContext(ctx, "SELECT V FROM "+name+" WHERE ID=?", i+1).Scan(&got); err != nil {
				t.Fatalf("read: %s", errorCode(err))
			}
			if !bytes.Equal(got, want) {
				t.Fatalf("BLOB roundtrip got=%x want=%x", got, want)
			}
		})
	}
}

func TestOracleReturningPrepare(t *testing.T) {
	db, ctx, name := oracleTable(t, "ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, V VARCHAR2(10)")
	query := "INSERT INTO " + name + " (V) VALUES (?) RETURNING ID INTO ?"
	for _, tc := range []struct {
		name, query string
		prepared    bool
	}{
		{"direct_control", query, false},
		{"prepared", query, true},
		{"prepared_block_control", "BEGIN " + query + "; END;", true},
	} {
		t.Run(tc.name, func(t *testing.T) {
			var id int64
			var err error
			if tc.prepared {
				stmt, prepareErr := db.PrepareContext(ctx, tc.query)
				if prepareErr != nil {
					t.Fatalf("prepare before execution: %s", errorCode(prepareErr))
				}
				defer func() { _ = stmt.Close() }()
				_, err = stmt.ExecContext(ctx, "probe", sql.Out{Dest: &id})
			} else {
				_, err = db.ExecContext(ctx, tc.query, "probe", sql.Out{Dest: &id})
			}
			if err != nil {
				t.Fatalf("execute: %s", errorCode(err))
			}
			if id <= 0 {
				t.Fatalf("generated ID=%d", id)
			}
		})
	}
}
